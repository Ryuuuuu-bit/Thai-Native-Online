'use strict';
const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const events = {}, values = {};
const toggle = {setAttribute:()=>{},addEventListener:(name,fn)=>events.toggle=fn};
const root = {classList:{toggle:()=>{}}};
const media = {matches:false,addEventListener:(name,fn)=>events[name]=fn};
const world = {style:{setProperty:(key,value)=>values[key]=value,removeProperty:key=>delete values[key]}};
const village = {addEventListener:(name,fn)=>events[name]=fn,getBoundingClientRect:()=>({left:10,top:20,width:100,height:100})};
vm.runInNewContext(fs.readFileSync('lobby-motion.js','utf8'), {document:{querySelector:s=>s==='.village'?village:world,getElementById:()=>toggle,documentElement:root},localStorage:{getItem:()=>null,setItem:()=>{}},matchMedia:()=>media});
events.pointermove({pointerType:'mouse',clientX:110,clientY:120});
assert.equal(values['--pan-x'],'-4px');
assert.equal(values['--pan-y'],'-2.5px');
events.pointerleave(); assert.deepEqual(values,{});
events.pointermove({pointerType:'touch',clientX:110,clientY:120}); assert.deepEqual(values,{});
media.matches=true; events.change();
events.pointermove({pointerType:'mouse',clientX:110,clientY:120}); assert.deepEqual(values,{});
events.toggle();
events.pointermove({pointerType:'mouse',clientX:110,clientY:120}); assert.equal(values['--pan-x'],'-4px');
events.toggle(); assert.deepEqual(values,{});
console.log('Lobby motion: mouse parallax, reset, touch and reduced-motion checks passed');
