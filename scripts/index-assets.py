"""Inspect source alpha and write frame metadata; never modifies image pixels."""
import json
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
def inspect(path):
    image = Image.open(ROOT / path).convert('RGBA')
    return np.asarray(image), image.width, image.height

def index(path, rows, names, trim=True):
    pixels, width, height = inspect(path)
    alpha = pixels[:, :, 3]
    frames = {}
    for row, name in enumerate(names):
        top, bottom = rows[row:row + 2]
        cuts = [0]
        for col in range(1, 4):
            center = round(width * col / 4)
            if trim:
                start, end = max(0, center-22), min(width, center+23)
                counts = (alpha[top:bottom, start:end] > 96).sum(axis=0)
                candidates = np.flatnonzero(counts == counts.min()) + start
                cuts.append(int(min(candidates, key=lambda x: abs(x-center))))
            else:
                cuts.append(center)
        cuts.append(width)
        for col in range(4):
            left, right = cuts[col:col+2]
            x, y, w, h = left, top, right-left, bottom-top
            if trim:
                yy, xx = np.where(alpha[top:bottom, left:right] > 16)
                assert len(xx), (path, name, col)
                x, y = left + int(xx.min()), top + int(yy.min())
                w, h = int(xx.max()-xx.min()+1), int(yy.max()-yy.min()+1)
            frames[f'{name}-{col}'] = {'x':x, 'y':y, 'w':w, 'h':h}
    return {'image':path, 'width':width, 'height':height, 'frames':frames}

actions = ['idle','move','aim','cast','hit','guard','victory','defeat']
# Boundaries reviewed against generated source: guide has seven drawn rows, with shared hit/guard poses.
guide = index('assets/sheets/guide-actions.png', [0,229,452,675,899,1121,1357,1600], ['idle','move','aim','cast','hit','victory','defeat'])
enemy = index('assets/sheets/enemy-actions.png', [0,242,462,672,883,1102,1308,1545,1774], actions)
guide['frames'].update({f'guard-{i}':dict(guide['frames'][f'hit-{min(2+i%2,3)}']) for i in range(4)})
for sheet in [guide,enemy]:
    sheet['baseHeight'] = max(sheet['frames'][f'idle-{i}']['h'] for i in range(4))
    sheet['actions'] = {name:{'frames':[f'{name}-{i}' for i in range(4)], 'fps':{'idle':4,'move':12,'aim':4,'cast':12,'hit':12,'guard':5,'victory':8,'defeat':7}[name], 'loop':name in ['idle','move','aim','guard']} for name in actions}
vfx = index('assets/sheets/combat-vfx.png', [0,266,535,782,1055,1263,1536], ['impact','burst','heal','shield','hit','victory'], False)
items = index('assets/items-concept-v1.png', [0,314,627,941,1254], ['r1','r2','r3','r4'])
ids = ['talisman','flame','lotus','cloth','robe','thread','moon','gold','enhancement_stone','experience_vial','healing_potion','mana_potion','summon_ticket','dungeon_key','treasure_chest','spirit_essence']
items['frames'] = dict(zip(ids, items['frames'].values()))
catalog = {'version':1,'items':items,'guide':guide,'enemy':enemy,'vfx':vfx,'layers':[
    {'id':'sky','type':'procedural','depth':-3},
    {'id':'valley','image':'assets/sheets/moon-valley.png','depth':-2},
    {'id':'forest','image':'assets/sheets/forest-frame.png','depth':-1},
    {'id':'terrain','image':'assets/battle-chibi-moonforest.png','depth':1,'collision':'server'},
    {'id':'fireflies','type':'procedural','depth':3}
]}
out = json.dumps(catalog,ensure_ascii=False,indent=2)
(ROOT/'assets/manifests/catalog.json').write_text(out,encoding='utf-8')
(ROOT/'asset-catalog.js').write_text('/* Generated by scripts/index-assets.py; source images unchanged. */\n(function(root){const catalog='+out+';if(typeof module!=="undefined"&&module.exports)module.exports=catalog;else root.NativeAssets=catalog;})(typeof globalThis!=="undefined"?globalThis:this);\n',encoding='utf-8')
print('Indexed', len(items['frames']), 'items, 28 guide poses (guard reuses hit), 32 enemy poses, 24 VFX frames.')
